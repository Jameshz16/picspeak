/// Soft Blue Design System — Border Radius
///
/// Consistent corner radii for the Soft Blue aesthetic.
class SbRadius {
  SbRadius._();

  /// Secondary radius — used for inputs, chips, and small elements (3px).
  static const double secondary = 3;

  /// Primary radius — used for buttons and cards (8px).
  static const double primary = 8;

  /// Medium radius — used for dialogs and larger containers (12px).
  static const double medium = 12;

  /// Large radius — used for bottom sheets and prominent containers (16px).
  static const double large = 16;

  /// Full radius — creates pill shapes (9999px).
  static const double full = 9999;
}
